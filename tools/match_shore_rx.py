#!/usr/bin/env python3
"""Match a boat TX ledger to real shore RX CSV observations by packet sequence."""
import argparse
import csv
import sys
from collections import Counter
from pathlib import Path


def read_rows(path, required_column):
    with Path(path).open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if not reader.fieldnames or required_column not in reader.fieldnames:
            raise ValueError(f"{path}: required column {required_column!r} not found")
        rows = list(reader)
    return rows


def identities(rows, column):
    counts = Counter(row[column].strip() for row in rows if row.get(column, "").strip())
    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-id", required=True, help="one boat reboot/run identifier; compare runs separately")
    parser.add_argument("--tx", required=True, help="boat *.tx.csv ledger")
    parser.add_argument("--rx", required=True, help="actual shore receiver CSV; never generated by this tool")
    parser.add_argument("--tx-seq-column", default="sequence")
    parser.add_argument("--rx-seq-column", required=True, help="sequence column name from the real receiver export")
    args = parser.parse_args()
    try:
        tx_rows = read_rows(args.tx, args.tx_seq_column)
        rx_rows = read_rows(args.rx, args.rx_seq_column)
        tx = identities(tx_rows, args.tx_seq_column)
        rx = identities(rx_rows, args.rx_seq_column)
    except (OSError, UnicodeError, csv.Error, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    tx_ids, rx_ids = set(tx), set(rx)
    matched = tx_ids & rx_ids
    tx_status = Counter(row.get("mac_result", "UNKNOWN") for row in tx_rows)
    print(f"run_id={args.run_id}")
    print(f"tx_rows={len(tx_rows)} tx_unique_sequences={len(tx_ids)} rx_rows={len(rx_rows)} rx_unique_sequences={len(rx_ids)}")
    print(f"sequence_matches={len(matched)} tx_without_rx={len(tx_ids - rx_ids)} rx_without_tx={len(rx_ids - tx_ids)}")
    print("boat_mac_result_counts=" + ",".join(f"{key}:{tx_status[key]}" for key in sorted(tx_status)))
    print(f"duplicate_tx_rows={sum(n - 1 for n in tx.values() if n > 1)} duplicate_rx_rows={sum(n - 1 for n in rx.values() if n > 1)}")
    print("Interpretation: sequence match means receiver CSV observation only; MAC ACK does not certify application parsing, storage, or display.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
